/**
 * @packageDocumentation
 *
 * The hints that webhint ships itself, and how much of each plumbline covers:
 * fully, in part, or not at all. It is data written by hand from webhint's
 * hint packages (the version is the one it was read from), so it changes when
 * webhint does and not with the catalogue.
 */

/** How much of a stock hint the checks of plumbline cover. */
export type StockStatus = 'covered' | 'partial' | 'not covered';

/** One hint of webhint's own. */
export interface StockHint {
  /** The npm package that holds it. */
  readonly package: string;
  readonly version: string;
  /** Its webhint id, such as `axe/aria`. */
  readonly id: string;
  readonly name: string;
  readonly description: string;
  /** Webhint's own category. */
  readonly category: string;
  readonly url: string;
  /** The webhint configurations that switch it on. */
  readonly configurations: readonly string[];
  /** The ids of the plumbline checks that cover it. */
  readonly coveredBy: readonly string[];
  readonly status: StockStatus;
  /** What the plumbline checks leave out, when they cover it in part or not at all. */
  readonly note?: string;
}

