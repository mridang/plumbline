/**
 * The taxonomy of the checks, as data: the display groups, the sections, the
 * closed lists of tags, targets and controls, where every check is placed,
 * which checks each profile adds and how a deployer fixes the recommended
 * ones. This file is the single source of truth for the placement of a check;
 * `taxonomy.ts` reads it and `defineHint` stamps it on the hint metadata.
 * Check ids, section ids, tag ids and set names are permanent.
 */

/** How strongly a check is recommended. */
export type Tier = 'recommended' | 'advanced' | 'experimental';

/** What a check looks at: the web host, the mail servers or the site as a whole. */
export type Target = 'web' | 'mail' | 'site';

/** Who can fix what a check finds. */
export type Control = 'deployer' | 'platform' | 'dns' | 'mail';

/** A display group: sections shown together, never a selector. */
export interface GroupDef {
  id: string;
  title: string;
  sections: readonly string[];
}

/** A section: the one home of a check. */
export interface SectionDef {
  id: string;
  title: string;
  /** The display group the section is shown under. */
  group: string;
  /** One plain sentence on what the section is about, for a newcomer. */
  intro: string;
  /** What the section holds. */
  scope: string;
  /** Who usually makes the fix. */
  fixer: string;
  /** Whether the section is in the default rule set (opt-in sections are not). Absent means it is. */
  defaultOn?: boolean;
}

/** The kinds of named sets. */
export type SetKind = 'top' | 'section' | 'profile';

/** A named set of checks, with the words the rules page uses for it. */
export interface SetDef {
  id: string;
  kind: SetKind;
  title: string;
  description: string;
  summary: string;
  whenToUse: string;
  /** The section of a per-section set. */
  section?: string;
}

/** Where one check is placed. */
export interface Placement {
  section: string;
  subsection: string;
  tags: readonly string[];
  tier: Tier;
  target: Target;
  control: Control;
  /** The catalogue version in which the check entered its current tier. */
  since: number;
  /** The month the check was added, `YYYY-MM`. */
  added: string;
  /** A note on the placement or the tier, when there is one. */
  note?: string;
}

/** A named set of checks that is not derived from tiers and sections. */
export interface ProfileDef extends SetDef {
  /** The sets the profile is the union of. */
  extends: readonly string[];
  /** Every check of the profile, sorted. */
  members: readonly string[];
}

/** How to fix a check on the two platforms the baseline is written for. */
export interface HowToFix {
  /** The fix, in a sentence. */
  fix: string;
  vercel?: string;
  cloudflare?: string;
}

